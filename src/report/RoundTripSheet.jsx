/**
 * The Round Trip Report sheet, drawn from the report JSON the backend builds (GET /reports/r/:token).
 * Layout follows round-trip-report-template.html. Lines with amount 0 are left out (the server already drops
 * zero on-route and off-route lines). The scanned voucher's row is highlighted on screen, not in print.
 */
import { useEffect } from "react";
import { clock, departure, dmy, fixed, money, plain, plural, stamp } from "./format";
import "./report.css";

const FONTS = "https://fonts.googleapis.com/css2?family=Source+Sans+3:wght@400;600;700&family=Source+Serif+4:opsz,wght@8..60,600&display=swap";

function useReportFonts() {
  useEffect(() => {
    if (document.querySelector(`link[href="${FONTS}"]`)) return;
    const l = document.createElement("link");
    l.rel = "stylesheet";
    l.href = FONTS;
    document.head.appendChild(l);
  }, []);
}

const COMPANY = "New Khan Road Runners";

export function RoundTripSheet({ report, printedAt = new Date() }) {
  useReportFonts();
  const { trip, legs, fuel, onroute, offroute, online, totals, expenses, summary, header, scannedVoucherId } = report;
  const draft = trip.status !== "finalized";
  const crew = [trip.driverName, trip.fareCollector].filter(Boolean).join(" / ") || "Name and signature";

  return (
    <article className={`sheet${draft ? " is-draft" : ""}`}>
      {/* ===== Masthead ===== */}
      <header className="masthead">
        <div className="brand">
          <div className="logo" aria-hidden="true">NEW<br />KHAN<br />ROAD<br />RUNNERS</div>
          <div>
            <h1 className="company">{COMPANY}</h1>
            <p className="doc-title"><strong>Round Trip Report</strong> · Income and expenses</p>
          </div>
        </div>
        <div className="stamp">
          <div className="stamp-text">
            <div className="muted">Report ID</div>
            <div className="report-id">{trip.id}</div>
            <div className="status">{draft ? "Draft" : "Finalized"}</div>
          </div>
          {header?.qrSvg && (
            <div>
              {/* SVG generated by the server's QR library from the report URL. */}
              <div className="qr" aria-label="QR code that opens the live report" dangerouslySetInnerHTML={{ __html: header.qrSvg }} />
              <div className="qr-caption">Scan for live report</div>
            </div>
          )}
        </div>
      </header>

      {/* ===== Trip facts ===== */}
      <dl className="facts">
        <div><dt>Fleet no.</dt><dd>{trip.fleetNo ?? "—"}</dd></div>
        <div><dt>Report date</dt><dd>{dmy(trip.reportDate)}</dd></div>
        <div><dt>Driver</dt><dd>{trip.driverName || "—"}</dd></div>
        <div><dt>Fare collector</dt><dd>{trip.fareCollector || "—"}</dd></div>
        <div><dt>Route</dt><dd>{trip.routeLabel}</dd></div>
        <div><dt>Time</dt><dd>{clock(trip.reportTime)}</dd></div>
        <div><dt>Distance</dt><dd>{fixed(trip.distanceKm)} km</dd></div>
        <div><dt>Diesel</dt><dd>{fixed(totals.dieselLitres)} L</dd></div>
        <div><dt>Average</dt><dd>{totals.avgKm === null ? "—" : `${fixed(totals.avgKm)} km/L`}</dd></div>
        <div><dt>Mobil oil</dt><dd>{fixed(trip.mobilOil)}</dd></div>
        <div><dt>Passengers</dt><dd>{totals.paxAll}</dd></div>
        <div><dt>Cargo / load</dt><dd>{money(totals.cargoLoad)}</dd></div>
      </dl>

      {/* ===== Income / sale ===== */}
      <section aria-labelledby="sales-h">
        <h2 id="sales-h">Income and sale by terminal</h2>
        <div className="scroll">
          <table className="sales">
            <thead>
              <tr>
                <th rowSpan={2}>Terminal</th>
                <th rowSpan={2}>Voucher no.</th>
                <th rowSpan={2}>Departure</th>
                <th colSpan={2} className="group split">Passengers</th>
                <th colSpan={3} className="group split">Income</th>
                <th rowSpan={2} className="num split">Total sale</th>
              </tr>
              <tr>
                <th className="num split">Terminal</th><th className="num">En route</th>
                <th className="num split">Terminal</th><th className="num">En route</th><th className="num">Online</th>
              </tr>
            </thead>
            {legs.map((leg) => (
              <tbody key={leg.id}>
                <tr className="leg">
                  <td colSpan={9}>
                    {leg.title}
                    <span className="leg-meta">
                      {plural(leg.rows.length, "terminal")} · {plural(leg.passengers, "passenger")}
                      {leg.legRef ? ` · ref ${leg.legRef}` : ""}
                    </span>
                  </td>
                </tr>
                {leg.rows.map((r) => (
                  <tr key={r.voucherId} className={r.voucherId === scannedVoucherId ? "is-scanned" : undefined}>
                    <td>{r.terminal}</td>
                    <td className="voucher">{r.voucherNo}</td>
                    <td>{departure(r.departureAt)}</td>
                    <td className="num split">{r.paxTerminal}</td>
                    <td className="num">{r.paxEnroute}</td>
                    <td className="num split">{money(r.incTerminal)}</td>
                    <td className="num">{money(r.incEnroute)}</td>
                    <td className="num">{money(r.incOnline)}</td>
                    <td className="num split">{money(r.totalSale)}</td>
                  </tr>
                ))}
              </tbody>
            ))}
            <tfoot>
              <tr>
                <td colSpan={3}>Trip total</td>
                <td className="num split">{totals.paxTerminal}</td>
                <td className="num">{totals.paxEnroute}</td>
                <td className="num split">{money(totals.incTerminal)}</td>
                <td className="num">{money(totals.incEnroute)}</td>
                <td className="num">{money(totals.incOnline)}</td>
                <td className="num split">{money(totals.totalSale)}</td>
              </tr>
            </tfoot>
          </table>
        </div>
      </section>

      {/* ===== Expenses + online ===== */}
      <section className="ledgers">
        <div className="ledger-stack">
          <div className="ledger">
            <h2>Diesel <span>entered by admin</span></h2>
            <table>
              <tbody>
                {fuel.length === 0 && <tr><td colSpan={2} className="empty">No fuel entered</td></tr>}
                {fuel.map((f, i) => (
                  <tr key={i}>
                    <td>{f.station} <span className="detail">{plain(f.litres)} L @ {plain(f.rate)}</span></td>
                    <td className="num">{money(f.amount)}</td>
                  </tr>
                ))}
                <tr className="sub"><td>Sub-total</td><td className="num">{money(expenses.diesel)}</td></tr>
              </tbody>
            </table>
          </div>
          <div className="ledger">
            <h2>On route <span>from terminal vouchers</span></h2>
            <table>
              <tbody>
                {onroute.map((l) => <tr key={l.name}><td>{l.name}</td><td className="num">{money(l.amount)}</td></tr>)}
                <tr className="sub"><td>Sub-total</td><td className="num">{money(expenses.onroute)}</td></tr>
                <tr className="grand"><td>Diesel + on route</td><td className="num">{money(expenses.dieselOnroute)}</td></tr>
              </tbody>
            </table>
          </div>
        </div>

        <div className="ledger">
          <h2>Off route <span>company rates</span></h2>
          <table>
            <tbody>
              {offroute.map((l) => <tr key={l.name}><td>{l.name}</td><td className="num">{money(l.amount)}</td></tr>)}
              <tr className="sub"><td>Sub-total</td><td className="num">{money(expenses.offroute)}</td></tr>
            </tbody>
          </table>
        </div>

        <div className="ledger">
          <h2>Online sale <span>web app, Bookme, Bookkaro</span></h2>
          <table>
            <tbody>
              {online.length === 0 && <tr><td colSpan={2} className="empty">No online bookings on this trip</td></tr>}
              {online.map((o) => (
                <tr key={o.platform}>
                  <td>{o.platform} <span className="detail">{plural(o.seats, "seat")}</span></td>
                  <td className="num">{money(o.amount)}</td>
                </tr>
              ))}
              <tr className="sub"><td>Total</td><td className="num">{money(summary.lessOnline)}</td></tr>
            </tbody>
          </table>
          <p className="detail" style={{ margin: "2mm 0 0" }}>
            Online sales are part of total sale but were paid to the platform, so they are subtracted before cash deposit.
          </p>
        </div>
      </section>

      {/* ===== Other expense / income ===== */}
      <section className="others">
        <div>
          <span>Other expense {trip.otherExpenseNote && <span className="detail">{trip.otherExpenseNote}</span>}</span>
          <strong>{money(trip.otherExpense)}</strong>
        </div>
        <div>
          <span>Other income {trip.otherIncomeNote && <span className="detail">{trip.otherIncomeNote}</span>}</span>
          <strong>{money(trip.otherIncome)}</strong>
        </div>
      </section>

      {/* ===== Settlement ===== */}
      <section className="settlement">
        <table className="summary">
          <thead>
            <tr><th /><th className="num">Sub-total</th><th className="num">Others</th><th className="num">Net total</th></tr>
          </thead>
          <tbody>
            <tr>
              <th>Total income <span className="detail">incl. cargo {money(totals.cargoLoad)}</span></th>
              <td className="num">{money(summary.incomeSub)}</td><td className="num">{money(summary.incomeOthers)}</td>
              <td className="num net">{money(summary.incomeNet)}</td>
            </tr>
            <tr>
              <th>Total expense</th>
              <td className="num">{money(summary.expenseSub)}</td><td className="num">{money(summary.expenseOthers)}</td>
              <td className="num net">{money(summary.expenseNet)}</td>
            </tr>
            <tr className="profit">
              <th>Profit</th>
              <td className="num">{money(summary.profitSub)}</td><td className="num">{money(summary.profitOthers)}</td>
              <td className="num net">{money(summary.profitNet)}</td>
            </tr>
            <tr><th>Less online sale</th><td /><td /><td className="num net">{money(summary.lessOnline)}</td></tr>
            <tr className="cash"><th>Net cash</th><td /><td /><td className="num net">{money(summary.netCash)}</td></tr>
          </tbody>
        </table>
        <div className="deposit">
          <div className="deposit-label">Cash deposit</div>
          <div className="deposit-amount"><small>PKR</small>{money(summary.cashDeposit)}</div>
          <div className="deposit-meta">
            Received by {trip.cashierName || "—"}
            <br />
            {trip.cashReceivedAt ? stamp(trip.cashReceivedAt) : "Not received yet"}
          </div>
        </div>
      </section>

      {/* ===== Sign-off ===== */}
      <section className="signoff">
        <div className="sig"><b>Cashier</b><span>{trip.cashierName || "Name and signature"}</span></div>
        <div className="sig"><b>Incharge</b><span>{trip.inchargeName || "Name and signature"}</span></div>
        <div className="sig"><b>Driver / fare collector</b><span>{crew}</span></div>
      </section>

      <footer className="colophon">
        <span>
          Trip {trip.id} · {trip.fleetNo ?? "—"} · {fixed(trip.distanceKm)} km · {fixed(totals.dieselLitres)} L diesel ·
          avg {totals.avgKm === null ? "—" : `${fixed(totals.avgKm)} km/L`}
        </span>
        <span>Printed {stamp(printedAt)} · Last updated {stamp(trip.updatedAt)}</span>
      </footer>
    </article>
  );
}
